@dataclass
class AMDToolArgs:
    config: Any = None
    launcher: str = "bash"  # bash, torchrun, or slurm
    script: str = "apps.main.train"  # The script to run.
    copy_code: bool = True  # Whether to copy code to dump dir
    dirs_exists_ok: bool = True  # Whether to copy new code and config and run regardless that dir exists
    override: bool = False  # Whether to delete dump dir and restart
    nodes: int = 1  # The number of nodes to run the job on. With launcher=slurm: the max number of nodes the GPUs may be spread over.
    ngpu: int = 1  # The number of GPUs required per node. With launcher=slurm: the TOTAL number of GPUs (one task each).
    ncpu: int = 16  # The number of CPUs allocated per task (per GPU with launcher=slurm).
    mem: str = ""  # The amount of memory to allocate (not enforced without SLURM). With launcher=slurm: memory per GPU.
    # SLURM options (launcher=slurm only)
    partition: str = "amdgpunodes"
    account: str = "amdgpus"
    qos: str = ""
    time: str = "1-00:00:00"
    nodelist: str = ""  # e.g. amdgpunode1,amdgpunode2 -- restrict to these nodes
    exclude: str = ""  # nodes to avoid
    gpu_type: str = ""  # e.g. mi350 -- avoid mixing GPU generations in one job
    socket_ifname: str = "^lo,docker"  # NCCL/GLOO interface for inter-node traffic
    hsa_override_gfx_version: str = "9.4.2"  # MI300X; set to "" for MI100/MI350 nodes
    anaconda: str = "default"  # The path to the anaconda environment.
    master_addr: str = "127.0.0.1"  # Master address for distributed training
    master_port: int = 29501  # Master port for rendezvous
    rocm_home: str = "/opt/rocm"  # Path to ROCm installation
    stdout: bool = False  # Whether to output to stdout or log files
    data_dir: str = "/data/lingua/"  # Local data directory


