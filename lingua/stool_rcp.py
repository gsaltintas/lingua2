"""
Job launcher for the EPFL RCP cluster (Run:ai on Kubernetes, no Slurm).

Accepts the same CLI as lingua.stool_ccdb, e.g.

    python -m lingua.stool_rcp ngpu=4 ncpu=8 mem=256G nodes=1 \
        script=apps.main.train config=apps/main/configs/flexitok/llama_1B.yaml

    python -m lingua.stool_rcp ngpu=1 ncpu=1 mem=64G nodes=1 script=apps.main.eval \
        config=["apps/main/configs/flexitok/eval/eval_base.yaml",apps/main/configs/flexitok/eval/xxx.yaml]

What it does:
  * rewrites cluster specific paths in the config (/fsx/..., /scratch/gsa/...) to `rcp_root`
  * copies the code + config into dump_dir (as stool_ccdb does)
  * writes {dump_dir}/submit.sh, which runs the script with torchrun inside the container
  * submits it with `runai submit` (nodes=1) or `runai submit-dist pytorch` (nodes>1),
    and saves the exact runai command to {dump_dir}/runai_submit.sh

Training jobs are non-interactive Run:ai jobs: they can be preempted and are restarted
by Run:ai, after which lingua resumes from the latest checkpoint in dump_dir.
Use launcher=bash to run submit.sh directly, e.g. from inside an interactive runai job.
`time`, `account`, `qos`, `partition`, ... are accepted for CLI compatibility but ignored.
"""

import os
import re
import shlex
import shutil
import subprocess
from dataclasses import dataclass
from typing import Any, MutableSequence

from omegaconf import OmegaConf

from lingua.args import dataclass_from_dict
from lingua.stool_ccdb import copy_dir

RCP_ROOT = "/mnt/nlp/scratch/home/altintas"


@dataclass
class StoolArgs:
    config: Any = None
    launcher: str = "runai"  # runai: submit a Run:ai job, bash: run submit.sh here (e.g. in an interactive job)
    script: str = "apps.main.train"  # The script to run.
    copy_code: bool = True  # Wether to copy code to dump dir
    dirs_exists_ok: bool = (
        True  # Wether to copy new code and config and run regardless that dir exists
    )
    override: bool = False  # Wether to delete dump dir and restart
    nodes: int = 1  # The number of nodes (pods) to run the job on.
    ngpu: int = 8  # The number of GPUs required per node.
    ncpu: int = 16  # The number of CPUs per GPU (pod gets ncpu * ngpu).
    mem: str = ""  # CPU memory per node, e.g. 256G. Empty = Run:ai default.
    venv: str = ""  # Path to the virtualenv. Defaults to <cwd>/.venv. Must live on the PVC.
    stdout: bool = False  # If False, also tee the output to {dump_dir}/logs/
    data_dir: str = ""  # Unused, kept for CLI compatibility with stool_ccdb.
    gpu_type: str = ""  # Run:ai node type (--node-type), e.g. h100 / a100-80g. Empty = any.

    # Run:ai specific
    project: str = "nlp-altintas"
    image: str = "registry.rcp.epfl.ch/nlp-altintas/uv"
    pvc: str = "nlp-scratch:/mnt/nlp/scratch"
    node_pool: str = "default"
    uid: int = 238299
    gid: int = 11131
    user: str = "altintas"
    rcp_root: str = RCP_ROOT  # Where /fsx/... and /scratch/gsa/... paths get remapped to.
    job_name: str = ""  # Defaults to the config name (sanitized for k8s).
    interactive: bool = False  # Interactive jobs are not preempted but count against guaranteed quota only.
    preemptible: bool = False  # Only meaningful with interactive=True.
    backoff_limit: int = 3  # Retries on failure (preemptions do not count).
    large_shm: bool = True  # Large /dev/shm for dataloader workers / NCCL.
    dry_run: bool = False  # Write files and print the runai command without submitting.

    # Slurm only, ignored here
    time: int = -1
    anaconda: str = ""
    constraint: str = ""
    exclude: str = ""
    account: str = ""
    qos: str = ""
    partition: str = ""
    priority: str = ""
    host: str = "rcp"


RUN_SCRIPT = """#!/bin/bash
# Generated by lingua.stool_rcp, runs inside the Run:ai container.
set -eo pipefail

export DUMP_DIR={dump_dir}
export LAUNCH_WITH="RUNAI"
export OMP_NUM_THREADS=1
export PYTORCH_CUDA_ALLOC_CONF="expandable_segments:True"
# export NCCL_DEBUG="INFO"

{go_to_code_dir}

if [ ! -x {venv}/bin/python ]; then
    echo "ERROR: {venv}/bin/python is not usable in the container."
    echo "The venv's base python must live on the PVC, recreate it with e.g."
    echo "  UV_PYTHON_INSTALL_DIR={rcp_root}/.local/share/uv/python uv venv --python 3.10"
    exit 1
fi
source {venv}/bin/activate

echo "Host: $(hostname)  python: $(which python)"
nvidia-smi -L || true

# PyTorchJob (runai submit-dist pytorch) sets MASTER_ADDR/MASTER_PORT and
# WORLD_SIZE/RANK as *number of pods* / *pod index*. torchrun then sets the
# per-process RANK/WORLD_SIZE/LOCAL_RANK that lingua.distributed reads.
if [ {nodes} -gt 1 ]; then
    NODE_RANK=${{RANK:-0}}
    DIST_ARGS="--nnodes={nodes} --node_rank=$NODE_RANK --master_addr=$MASTER_ADDR --master_port=$MASTER_PORT"
else
    NODE_RANK=0
    DIST_ARGS="--standalone --nnodes=1"
fi

LOG_FILE=$DUMP_DIR/logs/{job_name}_node${{NODE_RANK}}_$(date +%Y%m%d-%H%M%S).log
{log_comment}echo "Logging to $LOG_FILE"

torchrun $DIST_ARGS --nproc_per_node={ngpu} \\
    -m {script} config=$DUMP_DIR/base_config.yaml {log_redirect}
"""


def remap_paths(cfg: Any, rcp_root: str) -> Any:
    """Recursively rewrite paths from the other clusters to their RCP equivalents."""
    replacements = [
        ("/fsx/craffel/toksuite/lingua_logs", f"{rcp_root}/train"),
        ("/fsx/craffel/lingua_logs", f"{rcp_root}/train"),
        ("/scratch/gsa/train", f"{rcp_root}/train"),
        ("/scratch/craffel/lingua/data", f"{rcp_root}/data"),
        ("/scratch/gsa/data", f"{rcp_root}/data"),
    ]
    if isinstance(cfg, dict):
        return {k: remap_paths(v, rcp_root) for k, v in cfg.items()}
    if isinstance(cfg, list):
        return [remap_paths(v, rcp_root) for v in cfg]
    if isinstance(cfg, str):
        for old, new in replacements:
            if cfg.startswith(old):
                return new + cfg[len(old):]
    return cfg


def k8s_name(name: str) -> str:
    # Run:ai job names must be lowercase alphanumerics or '-', start with a letter,
    # and keep some room for suffixes
    name = re.sub(r"[^a-z0-9-]+", "-", name.lower()).strip("-")
    if not name[:1].isalpha():
        name = f"j-{name}"
    return name[:40].strip("-")


def validate_args(args: StoolArgs) -> None:
    assert args.ngpu > 0
    assert args.ncpu > 0
    assert args.nodes > 0
    assert args.launcher in ("runai", "bash"), args.launcher
    if args.time != -1:
        print(f"Note: time={args.time} is ignored, Run:ai jobs have no wall time limit.")

    args.venv = os.path.abspath(args.venv or os.path.join(os.getcwd(), ".venv"))
    pvc_mount = args.pvc.split(":", 1)[1]
    for path in (args.venv, args.config["dump_dir"]):
        if not path.startswith(pvc_mount):
            print(f"WARNING: {path} is not under the PVC mount {pvc_mount}, the container will not see it.")
    python = os.path.realpath(os.path.join(args.venv, "bin", "python"))
    if not python.startswith(pvc_mount):
        print(
            f"WARNING: the venv python resolves to {python}, which is not on the PVC.\n"
            f"Recreate the venv with UV_PYTHON_INSTALL_DIR={args.rcp_root}/.local/share/uv/python"
        )


def build_runai_command(args: StoolArgs, run_script: str) -> list:
    if args.nodes > 1:
        # One pod per node: a master pod plus nodes - 1 workers
        cmd = ["runai", "submit-dist", "pytorch", "--workers", str(args.nodes - 1)]
    else:
        cmd = ["runai", "submit"]
    cmd += [
        "-p", args.project,
        "--name", args.job_name,
        "--image", args.image,
        "--gpu", str(args.ngpu),
        "--cpu", str(args.ncpu * args.ngpu),
        "--pvc", args.pvc,
        "--node-pools", args.node_pool,
        "--run-as-uid", str(args.uid),
        "--run-as-gid", str(args.gid),
        "--backoff-limit", str(args.backoff_limit),
        "-e", f"HOME={args.rcp_root}",
        "-e", f"USER={args.user}",
        "-e", f"HF_HOME={args.rcp_root}/.cache/huggingface",
        "-e", f"UV_CACHE_DIR={args.rcp_root}/.cache/uv",
        "-e", f"UV_PYTHON_INSTALL_DIR={args.rcp_root}/.local/share/uv/python",
    ]
    if args.mem:
        cmd += ["--memory", args.mem]
    if args.gpu_type:
        cmd += ["--node-type", args.gpu_type]
    if args.large_shm:
        cmd += ["--large-shm"]
    if args.interactive and args.nodes == 1:
        cmd += ["--interactive"]
        if args.preemptible:
            cmd += ["--preemptible"]
    cmd += ["--command", "--", "bash", run_script]
    return cmd


def launch_job(args: StoolArgs):
    args.config = OmegaConf.create(
        remap_paths(OmegaConf.to_container(OmegaConf.create(args.config), resolve=True), args.rcp_root)
    )
    validate_args(args)
    dump_dir = args.config["dump_dir"]
    args.job_name = k8s_name(args.job_name or args.config["name"])
    print(f"dump_dir: {dump_dir}\njob name: {args.job_name}")

    print("Creating directories...")
    os.makedirs(dump_dir, exist_ok=args.dirs_exists_ok or args.override)
    if args.override:
        confirm = input(
            f"Are you sure you want to delete the directory '{dump_dir}'? This action cannot be undone. (yes/no): "
        )
        if confirm.lower() == "yes":
            shutil.rmtree(dump_dir)
            print(f"Directory '{dump_dir}' has been deleted.")
        else:
            print("Operation cancelled.")
            return
    os.makedirs(os.path.join(dump_dir, "logs"), exist_ok=True)
    if args.copy_code:
        os.makedirs(f"{dump_dir}/code", exist_ok=args.dirs_exists_ok)
        print("Copying code ...")
        copy_dir(os.getcwd(), f"{dump_dir}/code")

    print("Saving config file ...")
    with open(f"{dump_dir}/base_config.yaml", "w") as cfg:
        cfg.write(OmegaConf.to_yaml(args.config))

    run_script = f"{dump_dir}/submit.sh"
    with open(run_script, "w") as f:
        f.write(
            RUN_SCRIPT.format(
                dump_dir=dump_dir,
                go_to_code_dir=f"cd {dump_dir}/code/" if args.copy_code else f"cd {os.getcwd()}",
                venv=args.venv,
                rcp_root=args.rcp_root,
                nodes=args.nodes,
                ngpu=args.ngpu,
                script=args.script,
                job_name=args.job_name,
                log_comment="# " if args.stdout else "",
                log_redirect="" if args.stdout else '2>&1 | tee -a "$LOG_FILE"',
            )
        )
    os.chmod(run_script, 0o755)

    if args.launcher == "bash":
        cmd = ["bash", run_script]
    else:
        cmd = build_runai_command(args, run_script)
        with open(f"{dump_dir}/runai_submit.sh", "w") as f:
            f.write("#!/bin/bash\n" + shlex.join(cmd) + "\n")

    print(f"Submitting job with {args.launcher}:\n{shlex.join(cmd)}")
    if args.dry_run:
        print("Dry run, not submitting.")
        return
    subprocess.run(cmd, check=True)

    if args.launcher == "runai":
        print(f"Follow with: runai logs -p {args.project} -f {args.job_name}")
        print(f"Delete with: runai delete job -p {args.project} {args.job_name}")
    print("Done.")


if __name__ == "__main__":
    args = OmegaConf.from_cli()

    if isinstance(args.config, MutableSequence):
        args.config = OmegaConf.merge(*[OmegaConf.load(c) for c in args.config])
    else:
        args.config = OmegaConf.load(args.config)
    args = dataclass_from_dict(StoolArgs, args)
    launch_job(args)
